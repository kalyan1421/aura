#!/usr/bin/env python3
"""Exports the Equal Orbit mark (README.md geometry) to every launcher icon
and Play store graphic. Rasterised with Pillow at 4x and downsampled, so no
SVG renderer is needed. Run from anywhere:

    python3 design/brand/equal-orbit/export_icons.py

Writes:
- Android legacy launcher  apps/mobile/android/app/src/main/res/mipmap-*/ic_launcher.png
- Android adaptive icon    mipmap-*/ic_launcher_foreground.png, ic_launcher_monochrome.png,
                           mipmap-anydpi-v26/ic_launcher.xml, values/ic_launcher_background.xml
- iOS AppIcon set          apps/mobile/ios/Runner/Assets.xcassets/AppIcon.appiconset/*.png
- Play graphics            apps/mobile/store/android/graphics/icon-512.png, feature-graphic.png
"""

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[3]
MOBILE = ROOT / "apps/mobile"
RES = MOBILE / "android/app/src/main/res"
IOS = MOBILE / "ios/Runner/Assets.xcassets/AppIcon.appiconset"
STORE = MOBILE / "store/android/graphics"

SKY_DEEP = "#05060F"
STARLIGHT = "#F7E6B5"
TEXT = "#F2F0FF"
# (colour, start angle) on the 512 grid; angles clockwise from 3 o'clock.
ARCS = [("#F3BE67", 190), ("#5ACBBE", 280), ("#AE93FA", 10), ("#AFC3F0", 100)]
SWEEP, ORBIT_R, STROKE, CORE_R = 70, 150, 50, 54
SS = 4  # supersampling factor


def draw_mark(img, cx, cy, unit, mono=None):
    """Draws the mark centred on (cx, cy); `unit` = pixels per 512-grid unit."""
    import math

    d = ImageDraw.Draw(img)
    r_out = (ORBIT_R + STROKE / 2) * unit
    w = STROKE * unit
    cap = STROKE / 2 * unit
    for colour, start in ARCS:
        c = mono or colour
        d.arc([cx - r_out, cy - r_out, cx + r_out, cy + r_out], start, start + SWEEP, fill=c, width=round(w))
        for a in (start, start + SWEEP):
            x = cx + ORBIT_R * unit * math.cos(math.radians(a))
            y = cy + ORBIT_R * unit * math.sin(math.radians(a))
            d.ellipse([x - cap, y - cap, x + cap, y + cap], fill=c)
    r = CORE_R * unit
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=mono or STARLIGHT)


def render(size, *, background=SKY_DEEP, mark_scale=1.0, mono=None):
    """A square icon: the 512 grid mapped onto `size` px, mark scaled about the centre."""
    n = size * SS
    img = Image.new("RGBA", (n, n), background or (0, 0, 0, 0))
    draw_mark(img, n / 2, n / 2, n / 512 * mark_scale, mono)
    img = img.resize((size, size), Image.LANCZOS)
    return img.convert("RGB") if background else img


def save(img, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)


def android():
    legacy = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for density, px in legacy.items():
        save(render(px), RES / f"mipmap-{density}/ic_launcher.png")
        # Adaptive layers are 108dp; the mark's outer edge (radius 175 of 512)
        # sits at 31dp, inside the 33dp safe circle every mask keeps.
        fg = px * 108 // 48
        scale = (31 / 108) / (175 / 512)
        save(render(fg, background=None, mark_scale=scale), RES / f"mipmap-{density}/ic_launcher_foreground.png")
        save(render(fg, background=None, mark_scale=scale, mono="#FFFFFF"),
             RES / f"mipmap-{density}/ic_launcher_monochrome.png")
    (RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    (RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by design/brand/equal-orbit/export_icons.py -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by design/brand/equal-orbit/export_icons.py (skyDeep) -->\n"
        "<resources>\n"
        f'    <color name="ic_launcher_background">{SKY_DEEP}</color>\n'
        "</resources>\n"
    )


def ios():
    for entry in json.loads((IOS / "Contents.json").read_text())["images"]:
        pt = float(entry["size"].split("x")[0])
        px = round(pt * int(entry["scale"].rstrip("x")))
        save(render(px), IOS / entry["filename"])  # RGB: App Store rejects alpha


def font(size, bold=False):
    for path, index in [("/System/Library/Fonts/Avenir Next.ttc", 5 if bold else 7),
                        ("/System/Library/Fonts/Helvetica.ttc", 1 if bold else 0)]:
        try:
            return ImageFont.truetype(path, size, index=index)
        except OSError:
            continue
    return ImageFont.load_default()


def store():
    save(render(512), STORE / "icon-512.png")
    # Feature graphic 1024x500: mark left, wordmark and tagline right.
    w, h = 1024, 500
    img = Image.new("RGB", (w * SS, h * SS), SKY_DEEP)
    draw_mark(img, 270 * SS, 250 * SS, 360 / 350 * SS)
    d = ImageDraw.Draw(img)
    d.text((500 * SS, 250 * SS), "Aura", font=font(132 * SS, bold=True), fill=TEXT, anchor="ls")
    d.text((504 * SS, 318 * SS), "Every feeling belongs.", font=font(44 * SS), fill="#AFC3F0", anchor="ls")
    save(img.resize((w, h), Image.LANCZOS), STORE / "feature-graphic.png")


if __name__ == "__main__":
    android()
    ios()
    store()
    print("Equal Orbit icons exported.")
