import 'dart:convert';
import 'dart:io';

import 'package:aura/src/features/support/crisis_lexicon.dart';
import 'package:aura/src/features/support/crisis_lexicon_data.dart';
import 'package:flutter_test/flutter_test.dart';

/// The bundled lexicon is the contract's (contracts/safety): the generated
/// Dart copy matches crisis_lexicon.v1.json, and the matcher passes every
/// shared vector the NestJS worker will also have to pass.
void main() {
  const dir = '../../contracts/safety';
  final lexicon = jsonDecode(
    File('$dir/crisis_lexicon.v1.json').readAsStringSync(),
  ) as Map<String, dynamic>;
  final vectors = jsonDecode(
    File('$dir/crisis_lexicon.vectors.json').readAsStringSync(),
  ) as Map<String, dynamic>;

  test('crisis_lexicon_data.dart is generated from the current JSON '
      '(run python3 tool/gen_lexicon.py)', () {
    expect(crisisLexiconVersion, lexicon['version']);
    final entries = (lexicon['entries'] as List).cast<Map<String, dynamic>>();
    expect(crisisLexiconEntries, hasLength(entries.length));
    for (final (i, e) in entries.indexed) {
      final bundled = crisisLexiconEntries[i];
      expect(bundled.id, e['id']);
      expect(bundled.language, e['language']);
      expect(bundled.kind, e['kind']);
      expect(bundled.stem, e['stem'] ?? false, reason: bundled.id);
      expect(bundled.forms, [
        e['phrase'],
        ...(e['variants'] as List? ?? const []),
      ], reason: bundled.id);
    }
  });

  test(
    'shipped languages have entries; Hindi and Hinglish are placeholders',
    () {
      final byLanguage = <String, int>{};
      for (final e in crisisLexiconEntries) {
        byLanguage[e.language] = (byLanguage[e.language] ?? 0) + 1;
      }
      for (final language in ['en', 'te', 'te-Latn']) {
        expect(byLanguage[language], greaterThan(0), reason: language);
        expect(
          crisisLexiconEntries.any(
            (e) => e.language == language && e.kind == 'crisis',
          ),
          isTrue,
          reason: '$language has crisis phrases',
        );
      }
      expect(byLanguage['hi'], isNull);
      expect(byLanguage['hi-Latn'], isNull);
      final languages = lexicon['languages'] as Map<String, dynamic>;
      expect(
        languages.keys,
        containsAll(['en', 'te', 'te-Latn', 'hi', 'hi-Latn']),
      );
    },
  );

  test('every phrase and variant, on its own, gets its entry\'s kind', () {
    for (final e in crisisLexiconEntries) {
      final expected = e.kind == 'crisis'
          ? LexiconVerdict.crisis
          : LexiconVerdict.soft;
      for (final form in e.forms) {
        expect(lexiconVerdict(form), expected, reason: '${e.id}: "$form"');
      }
    }
  });

  test('the file header says it still needs review (A9)', () {
    final source = File('lib/src/features/support/crisis_lexicon_data.dart')
        .readAsStringSync();
    expect(source, contains('NEEDS NATIVE + SAFE-MESSAGING REVIEW (A9)'));
    expect(source, contains('GENERATED by tool/gen_lexicon.py'));
  });

  group('contract vectors', () {
    test('are written for this lexicon version', () {
      expect(vectors['lexicon_version'], lexicon['version']);
    });
    for (final c in (vectors['cases'] as List).cast<Map<String, dynamic>>()) {
      final text = c['text'] as String;
      final verdict = LexiconVerdict.values.byName(c['verdict'] as String);
      test('${c['verdict']}: ${jsonEncode(text)} (${c['why']})', () {
        expect(lexiconVerdict(text), verdict);
        expect(noteNeedsSupport(text), verdict == LexiconVerdict.crisis);
      });
    }
  });
}
