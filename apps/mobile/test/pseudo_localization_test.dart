/// PRD 18 "Pseudo-localized build before each milestone": every string
/// accented, ~40% longer and bracketed (test/pseudo, generated by
/// tool/gen_pseudo_l10n.py from the real message catalogue), on a small
/// phone. Nothing may overflow, and brackets show where text is cut. The
/// Telugu and Hindi runs at 200% live with each screen's own tests.

class _QuietHaptics implements BreathHaptics {
  @override
  dynamic noSuchMethod(Invocation invocation) => null;
}

Future<void> _pumpPseudo(WidgetTester tester, Widget child) async {
  // A small phone (360 × 740 dp): the longest strings have the least room.
  tester.view.physicalSize = const Size(360 * 3, 740 * 3);
  tester.view.devicePixelRatio = 3;
  addTearDown(tester.view.reset);
  await tester.pumpWidget(
    ProviderScope(
      overrides: [
        ...testOverrides(db: memoryDb()),
        breathHapticsProvider.overrideWithValue(_QuietHaptics()),
      ],
      child: MaterialApp(
        theme: buildAuraTheme(const Locale('en')),
        locale: const Locale('en'),
        supportedLocales: AppLocalizations.supportedLocales,
        localizationsDelegates: const [
          PseudoLocalizationsDelegate(),
          ...systemLocalizationDelegates,
        ],
        home: child,
      ),
    ),
  );
  await settleIo(tester);
}

Future<void> _scrollAll(WidgetTester tester) async {
  final scrollables = find.byType(Scrollable);
  if (scrollables.evaluate().isEmpty) return;
  for (var i = 0; i < 12; i++) {
    await tester.drag(scrollables.first, const Offset(0, -400));
    await tester.pump(const Duration(milliseconds: 50));
  }
}

void main() {
  test('pseudo strings are longer, accented and bracketed; brands stay', () {
    expect(pseudo('Save'), '[Šåvé ··]');
    expect(pseudo('Open Aura Plus'), startsWith('[Öpéñ Aura Plus'));
    expect(pseudo(''), '');
  });

  test('the pseudo catalogue is current (tool/gen_pseudo_l10n.py --check)', () {
    final r = Process.runSync('python3', [
      'tool/gen_pseudo_l10n.py',
      '--check',
    ]);
    expect(r.exitCode, 0, reason: '${r.stdout}${r.stderr}');
  });

  final screens = <String, Widget>{
    'check-in': const CheckInScreen(),
    'Sanctuary': const SanctuaryScreen(),
    'Settings': const SettingsScreen(),
    'Safety Center': const SafetyCenterScreen(),
    '"I need help now" button': const Scaffold(
      body: Center(child: HelpNowButton()),
    ),
    'grievance form': const GrievanceFormScreen(),
    'data export': const DataExportScreen(),
  };

  for (final MapEntry(key: name, value: screen) in screens.entries) {
    testWidgets('$name: nothing overflows with pseudo strings', (tester) async {
      await _pumpPseudo(tester, screen);
      expect(tester.takeException(), isNull);
      // A pseudo string is on screen (the catalogue is really in use).
      expect(find.textContaining('['), findsWidgets);
      await _scrollAll(tester);
      expect(tester.takeException(), isNull);
      await tester.pumpWidget(const SizedBox());
      await tester.pump(const Duration(seconds: 1));
    });
  }
}
