#!/usr/bin/env python3
"""Pseudo-localized AppLocalizations for the pseudo-localization run (PRD 18
"Pseudo-localized build before each milestone").

    python3 tool/gen_pseudo_l10n.py            # writes test/pseudo/app_localizations_pseudo.dart
    python3 tool/gen_pseudo_l10n.py --check    # fails when it is stale

Reads the generated `lib/l10n/app_localizations.dart` (gen-l10n output) and
writes a TEST-ONLY subclass of the English localizations in which every message
is accented and about 40% longer, with brackets that show truncation: "Save" →
"[Šåvé ··]". Placeholders and plurals are filled by the English class first,
so numbers, names and ICU forms stay real. Never part of the app: nothing under
lib/ imports it, and no build ships it. test/pseudo_localization_test.dart pumps
key screens with it on a small phone and fails on any overflow.
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SRC = os.path.join(ROOT, "lib", "l10n", "app_localizations.dart")
OUT = os.path.join(ROOT, "test", "pseudo", "app_localizations_pseudo.dart")

# `String get key;` or `String key(Type a, Type b);` (possibly over several lines) inside the abstract class.
GETTER = re.compile(r"^\s*String get (\w+);", re.M)
METHOD = re.compile(r"^\s*String (\w+)\(([^)]*)\);", re.M)


def members(src: str):
    body = src[src.index("abstract class AppLocalizations"):]
    body = body[: body.index("\nclass _AppLocalizationsDelegate")]
    out = []
    for m in GETTER.finditer(body):
        out.append((m.start(), m.group(1), None))
    for m in METHOD.finditer(body):
        params = [p.strip() for p in m.group(2).replace("\n", " ").split(",") if p.strip()]
        out.append((m.start(), m.group(1), params))
    return [(name, params) for _, name, params in sorted(out)]


def render(src: str) -> str:
    lines = [
        "// GENERATED by tool/gen_pseudo_l10n.py from lib/l10n/app_localizations.dart. Do not edit.",
        "// Test-only pseudo-localization (PRD 18): accented, ~40% longer, bracketed English.",
        "// ignore_for_file: non_constant_identifier_names, lines_longer_than_80_chars",
        "import 'package:aura/l10n/app_localizations_en.dart';",
        "",
        "import 'pseudo.dart';",
        "",
        "class AppLocalizationsPseudo extends AppLocalizationsEn {",
        "  AppLocalizationsPseudo() : super('en');",
        "",
    ]
    for name, params in members(src):
        if name == "appTitle":
            continue  # the brand stays as it is
        if params is None:
            lines.append(f"  @override")
            lines.append(f"  String get {name} => pseudo(super.{name});")
        else:
            args = ", ".join(p.split()[-1] for p in params)
            lines.append(f"  @override")
            lines.append(f"  String {name}({', '.join(params)}) => pseudo(super.{name}({args}));")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def formatted(code: str) -> str:
    """The code as `dart format` leaves it (so the checked-in file and the check agree)."""
    with tempfile.NamedTemporaryFile("w", suffix=".dart", delete=False, encoding="utf-8") as t:
        t.write(code)
        path = t.name
    try:
        subprocess.run(["dart", "format", path], check=True, capture_output=True)
        with open(path, encoding="utf-8") as f:
            return f.read()
    finally:
        os.unlink(path)


def main() -> None:
    with open(SRC, encoding="utf-8") as f:
        out = formatted(render(f.read()))
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != out:
                raise SystemExit("gen_pseudo_l10n: test/pseudo/app_localizations_pseudo.dart is stale; run tool/gen.sh l10n")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
