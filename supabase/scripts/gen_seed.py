#!/usr/bin/env python3
"""Regenerate supabase/seed.sql from contracts/moods.json.

Usage (from repo root):
  python3 supabase/scripts/gen_seed.py                      # refresh supabase/seed.sql (local only)
  python3 supabase/scripts/gen_seed.py --migration <stamp>  # also write migrations/<stamp>_catalogue.sql
The catalogue is reference data that production needs too, so every change to contracts/moods.json
ships as a new timestamped catalogue migration. Both outputs are idempotent upserts.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "contracts" / "moods.json"
OUT = ROOT / "supabase" / "seed.sql"

QUADRANTS = {"storm", "rain", "moonlight", "sunrise"}


def lit(value: str) -> str:
    """SQL string literal (standard_conforming_strings = on)."""
    return "'" + value.replace("'", "''") + "'"


def jsonb(obj: dict) -> str:
    return lit(json.dumps(obj, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    moods = data["moods"]
    presets = data["presetHabits"]

    ids = [m["id"] for m in moods]
    assert len(ids) == len(set(ids)), "duplicate mood id"
    assert all(m["quadrant"] in QUADRANTS for m in moods), "unknown quadrant"
    assert all("en" in m["names"] for m in moods), "every mood needs an en name"
    assert all("en" in p["names"] for p in presets), "every preset habit needs an en name"

    lines = [
        "-- GENERATED by supabase/scripts/gen_seed.py from contracts/moods.json — do not edit by hand.",
        f"-- {len(moods)} moods, {len(presets)} preset habits.",
        "",
        "insert into public.moods (id, quadrant, sort, names) values",
    ]
    rows = [
        f"  ({lit(m['id'])}, {lit(m['quadrant'])}, {int(m['sort'])}, {jsonb(m['names'])})"
        for m in sorted(moods, key=lambda m: m["sort"])
    ]
    lines.append(",\n".join(rows))
    lines.append(
        "on conflict (id) do update set quadrant = excluded.quadrant, sort = excluded.sort, names = excluded.names;"
    )
    lines += ["", "insert into public.preset_habits (key, names) values"]
    rows = [f"  ({lit(p['key'])}, {jsonb(p['names'])})" for p in presets]
    lines.append(",\n".join(rows))
    lines.append("on conflict (key) do update set names = excluded.names;")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    if len(sys.argv) == 3 and sys.argv[1] == "--migration":
        mig = ROOT / "supabase" / "migrations" / f"{sys.argv[2]}_catalogue.sql"
        mig.write_text("\n".join(lines).replace("-- GENERATED", "-- Catalogue migration GENERATED", 1), encoding="utf-8")
        print(f"wrote {mig.relative_to(ROOT)}")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(moods)} moods, {len(presets)} preset habits")


if __name__ == "__main__":
    main()
