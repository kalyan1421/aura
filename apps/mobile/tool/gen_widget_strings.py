#!/usr/bin/env python3
"""Native home-screen widget strings (F11) from the Flutter ARB files.

    python3 tool/gen_widget_strings.py          # write
    python3 tool/gen_widget_strings.py --check  # exit 1 if a file is stale

Single source: tool/l10n/widget.py -> lib/l10n/app_*.arb (tool/l10n_source.py)
-> this script -> the native fallback copies:

  * iOS:     ios/AuraWidget/Localizable.xcstrings (String Catalog)
  * Android: android/app/src/main/res/values*/widget_strings.xml

The running widget shows the copy the app hands it (the app's own language,
Tenglish and Hinglish included); these native copies only cover the moments
before the app has published anything (a fresh install, the widget gallery),
so they follow the phone's language. test/widget_strings_test.dart
fails if they drift from the ARB files. Run through tool/gen.sh.
"""
import json
import os
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
ARB_DIR = os.path.join(ROOT, "lib", "l10n")
IOS_OUT = os.path.join(ROOT, "ios", "AuraWidget", "Localizable.xcstrings")
ANDROID_RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

# Keys the native widgets use on their own (no placeholders).
WIDGET_NATIVE_KEYS = [
    "widget_prompt",
    "widget_checkIn",
    "widget_doneToday",
    "widget_saved",
    "widget_needHelp",
    "widget_openApp",
    "widget_openAppDiscreet",
    "widget_back",
    "widget_galleryName",
    "widget_galleryDescription",
    "widget_lockGalleryName",
    "widget_lockGalleryDescription",
]

# ARB locale -> (iOS language id, Android values-* qualifier).
LOCALES = [
    ("en", "en", "values"),
    ("te", "te", "values-te"),
    ("te_Latn", "te-Latn", "values-b+te+Latn"),
    ("hi", "hi", "values-hi"),
    ("hi_Latn", "hi-Latn", "values-b+hi+Latn"),
]

HEADER = "GENERATED by tool/gen_widget_strings.py from lib/l10n/app_*.arb. Do not edit."


def load_arbs():
    out = {}
    for arb, _, _ in LOCALES:
        with open(os.path.join(ARB_DIR, f"app_{arb}.arb"), encoding="utf-8") as f:
            data = json.load(f)
        values = {}
        for key in WIDGET_NATIVE_KEYS:
            value = data.get(key)
            if not isinstance(value, str) or not value.strip():
                raise SystemExit(f"gen_widget_strings: {key} missing in app_{arb}.arb")
            if "{" in value:
                raise SystemExit(f"gen_widget_strings: {key} has a placeholder (native keys must not)")
            values[key] = value
        out[arb] = values
    return out


def ios_catalog(arbs):
    strings = {}
    for key in WIDGET_NATIVE_KEYS:
        locs = {}
        for arb, lang, _ in LOCALES:
            locs[lang] = {"stringUnit": {"state": "translated", "value": arbs[arb][key]}}
        strings[key] = {"comment": HEADER, "extractionState": "manual", "localizations": locs}
    catalog = {"sourceLanguage": "en", "strings": strings, "version": "1.0"}
    return json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def android_xml(values):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
    for key in WIDGET_NATIVE_KEYS:
        text = escape(values[key]).replace("'", "\\'").replace('"', '\\"')
        lines.append(f'    <string name="{key}">{text}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def outputs():
    arbs = load_arbs()
    files = {IOS_OUT: ios_catalog(arbs)}
    for arb, _, qualifier in LOCALES:
        files[os.path.join(ANDROID_RES, qualifier, "widget_strings.xml")] = android_xml(arbs[arb])
    return files


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, content in outputs().items():
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                current = f.read()
        if current == content:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    if stale:
        raise SystemExit("gen_widget_strings: stale (run bash tool/gen.sh l10n):\n  " + "\n  ".join(stale))


if __name__ == "__main__":
    main()
