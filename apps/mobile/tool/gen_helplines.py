#!/usr/bin/env python3
"""Helpline directory -> lib/src/features/support/helplines_data.dart
(+ the NestJS copy, server/aura-api/src/remote-config/helplines/helplines-contract.data.ts).

    python3 tool/gen_helplines.py            # write both files
    python3 tool/gen_helplines.py --check    # exit 1 if either is out of date

Reads contracts/safety/helplines.v1.json (the reviewed baseline every app build
bundles; schema: contracts/safety/helplines.schema.json), validates it with the
same rules as the app (compileHelplines) and the server (helplines/document.ts)
and writes a const Dart copy — the offline fallback of the crisis sheet, used
until a signed `helplines` bundle verifies — and the server's copy (the baseline
that published versions are compared with). A wrong number is a P0 bug:
re-verify quarterly (PRD 18 "Helplines by country").
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SOURCE = os.path.join(ROOT, "contracts", "safety", "helplines.v1.json")
OUT = os.path.join(HERE, "..", "lib", "src", "features", "support", "helplines_data.dart")
SERVER_OUT = os.path.join(
    ROOT, "server", "aura-api", "src", "remote-config", "helplines", "helplines-contract.data.ts"
)

LOCALES = ["en", "te", "te-Latn", "hi", "hi-Latn"]
AUDIENCES = {"everyone", "minors"}
COUNTRY = re.compile(r"^[A-Z]{2}$")
LINE_ID = re.compile(r"^[a-z]{2}\.[a-z0-9_]{1,40}$")
NUMBER = re.compile(r"^[0-9+() -]{2,24}$")
DIAL = re.compile(r"^[0-9]{2,15}$")
CONTROL = re.compile(r"[\x00-\x1f\x7f]")
DAY = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")


def fail(message):
    raise SystemExit(f"gen_helplines: {message}")


def validate(doc):
    if doc.get("name") != "aura.helplines":
        fail("name must be 'aura.helplines'")
    version = doc.get("version")
    if not isinstance(version, int) or isinstance(version, bool) or not 1 <= version <= 1_000_000:
        fail("version must be a positive integer")
    if "verifiedOn" in doc and not (isinstance(doc["verifiedOn"], str) and DAY.match(doc["verifiedOn"])):
        fail("verifiedOn must be YYYY-MM-DD")
    countries = doc.get("countries")
    if not isinstance(countries, dict) or not 1 <= len(countries) <= 250:
        fail("countries must be an object with 1-250 regions")
    seen = set()
    for code, lines in countries.items():
        if not COUNTRY.match(code):
            fail(f"{code!r}: a region is an ISO 3166-1 alpha-2 code in capitals")
        if not isinstance(lines, list) or not 1 <= len(lines) <= 10:
            fail(f"{code}: 1-10 lines")
        if not any(isinstance(l, dict) and l.get("audience") == "everyone" for l in lines):
            fail(f"{code}: needs at least one line for everyone")
        for line in lines:
            if not isinstance(line, dict):
                fail(f"{code}: a line must be an object")
            lid = line.get("id")
            if not isinstance(lid, str) or not LINE_ID.match(lid) or not lid.startswith(code.lower() + "."):
                fail(f"{code}: id {lid!r} must be '{code.lower()}.<snake_case>'")
            if lid in seen:
                fail(f"{lid}: duplicate id")
            seen.add(lid)
            number, dial = line.get("number"), line.get("dial")
            if not isinstance(number, str) or not NUMBER.match(number):
                fail(f"{lid}: number must be digits with spaces, dashes, + or ()")
            if not isinstance(dial, str) or not DIAL.match(dial):
                fail(f"{lid}: dial must be 2-15 digits")
            if re.sub(r"[^0-9]", "", number) != dial:
                fail(f"{lid}: the digits of number must be exactly dial (what is shown is what is dialled)")
            if line.get("audience") not in AUDIENCES:
                fail(f"{lid}: audience must be everyone or minors")
            names = line.get("names")
            if not isinstance(names, dict) or not isinstance(names.get("en"), str):
                fail(f"{lid}: names needs en")
            for loc, name in names.items():
                if loc not in LOCALES:
                    fail(f"{lid}: unknown locale {loc!r}")
                if not isinstance(name, str) or not name.strip() or len(name) > 80 or CONTROL.search(name):
                    fail(f"{lid}: names.{loc} must be 1-80 characters, no control characters")
    return doc


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def dart(doc):
    out = [
        "// GENERATED by tool/gen_helplines.py from contracts/safety/helplines.v1.json.",
        "// Do not edit by hand: edit the JSON (contracts/safety/README.md), then run",
        "// `python3 tool/gen_helplines.py` (tool/gen.sh runs it too).",
        "//",
        "// Numbers: re-verify quarterly (PRD 18). te / te-Latn names: native review",
        "// (docs/l10n/helplines-and-emails.md).",
        "",
        "part of 'helplines.dart';",
        "",
        "/// The bundled directory's `version`.",
        f"const int bundledHelplinesVersion = {doc['version']};",
        "",
        "/// When the bundled numbers were last checked by a person.",
        f"const String bundledHelplinesVerifiedOn = {dart_str(doc.get('verifiedOn', ''))};",
        "",
        "/// Region → lines, in the order the app lists them.",
        "const Map<String, List<HelplineEntry>> bundledHelplineCountries = {",
    ]
    for code, lines in doc["countries"].items():
        out.append(f"  {dart_str(code)}: [")
        for l in lines:
            names = ", ".join(f"{dart_str(k)}: {dart_str(v)}" for k, v in l["names"].items())
            out += [
                "    HelplineEntry(",
                f"      id: {dart_str(l['id'])},",
                f"      number: {dart_str(l['number'])},",
                f"      dial: {dart_str(l['dial'])},",
                f"      minorsOnly: {'true' if l['audience'] == 'minors' else 'false'},",
                f"      names: {{{names}}},",
                "    ),",
            ]
        out.append("  ],")
    out.append("};")
    return "\n".join(out) + "\n"


def typescript(doc):
    body = json.dumps(doc, ensure_ascii=False, indent=2)
    return "\n".join([
        "// GENERATED by apps/mobile/tool/gen_helplines.py from contracts/safety/helplines.v1.json. Do not edit by hand:",
        "// edit the JSON (see contracts/safety/README.md), then run `python3 tool/gen_helplines.py` in apps/mobile.",
        "",
        "/** contracts/safety/helplines.v1.json: the directory every app build bundles (its offline fallback). */",
        f"export const BASELINE_HELPLINES: unknown = {body};",
        "",
    ])


def main():
    check = "--check" in sys.argv[1:]
    with open(SOURCE, encoding="utf-8") as f:
        doc = validate(json.load(f))
    stale = []
    for path, content in ((OUT, dart(doc)), (SERVER_OUT, typescript(doc))):
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == content:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"gen_helplines: wrote {os.path.relpath(path, ROOT)}")
    if stale:
        fail("out of date (run python3 tool/gen_helplines.py): " + ", ".join(stale))


if __name__ == "__main__":
    main()
